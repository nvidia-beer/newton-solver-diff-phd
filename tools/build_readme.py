"""Generate the README from project metadata, method notes and discovered examples."""

import argparse
import html
import json
import posixpath
import re
import runpy
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def project(root=ROOT):
    metadata = tomllib.loads((root / "pyproject.toml").read_text())
    name = metadata["project"]["name"]
    package = name.replace("-", "_")
    launcher = root / "src" / package / "examples" / "__main__.py"
    examples = runpy.run_path(str(launcher))["discover"]()
    return metadata["project"], package, examples


def document_text(path, root):
    """Keep source-file links valid both in docs/ and in the generated root README."""

    def replace(match):
        target = match.group(2)
        if target.startswith(("https://", "http://", "#", "mailto:")):
            return match.group(0)
        rebased = posixpath.normpath(str(path.parent.relative_to(root) / target))
        return f"{match.group(1)}({rebased})"

    source = re.sub(r"^# ", "## ", path.read_text().strip(), count=1)
    return re.sub(r"(!?\[[^\]\n]*\])\(([^\s)]+)\)", replace, source)


def make_readme(root=ROOT, *, require_videos=False):
    metadata, package, examples = project(root)
    name = metadata["name"]
    dependencies = ", ".join(f"`{item}`" for item in metadata.get("dependencies", []))
    text = [
        "<!-- Generated by tools/build_readme.py; edit pyproject.toml and the sources in docs/. -->",
        f"# {name}\n",
        metadata["description"] + ".\n",
        "## Run\n",
        "From this directory:\n",
        "```bash\n./docker/build.sh\n./docker/run.sh                 # Choose an automatically discovered example.\n./docker/run.sh --list          # List examples without Docker or GPU access.\n./docker/run.sh <example>       # Run one example.\n```\n",
        "For local development:\n",
        f"```bash\nuv sync --locked --extra examples\nuv run --locked python -m {package}.examples\n```\n",
        "Linux x86-64 or ARM64, Python 3.12. CUDA runs need an NVIDIA driver compatible "
        "with the locked CUDA 13 Warp wheel; Docker GPU runs also need NVIDIA Container Toolkit. "
        "Use `--cpu --headless` before the example name for supported CPU scenes. "
        "Visual Docker runs use the local X11 display and a readable `XAUTHORITY` file. "
        "Use `./docker/run.sh -- COMMAND ...` for an arbitrary container command. "
        "Source is mounted from this directory; rebuild after changing dependencies.\n",
        "## Dependencies\n",
        f"Installed runtime packages: {dependencies}. "
        "No sibling solver package or external source checkout is required. "
        "The `examples` extra supplies the viewer and any USD/robot dependencies; "
        "`uv.lock` fixes their versions. Example-specific data requirements are listed below.\n",
    ]
    usage = root / "docs" / "usage.md"
    if usage.exists():
        text.append(document_text(usage, root) + "\n")
    method = root / "docs" / "method.md"
    if not method.exists():
        raise ValueError("docs/method.md must explain the implemented method and cite its papers")
    text.append(document_text(method, root) + "\n")
    papers = root / "docs" / "papers.md"
    if papers.is_file():
        text.append(document_text(papers, root) + "\n")
    text.extend(
        [
            "## Examples\n",
            "One demonstration clip per example. Click a preview to open its MP4. "
            "Videos show simulated motion rendered offline; playback rate is not a performance measurement.\n",
        ]
    )
    cells = []
    for example, (description, _, module) in examples.items():
        media = root / "docs" / "media"
        clip = media / f"{example}.mp4"
        preview = next(
            (media / f"{example}{ext}" for ext in (".gif", ".jpg") if (media / f"{example}{ext}").is_file()), None
        )
        source = "src/" + package + "/examples/" + module.replace(".", "/") + ".py"
        cell = f"**[{example}]({source})**<br>{html.escape(description)}<br>"
        if clip.is_file() and preview:
            cell += f'<a href="docs/media/{clip.name}"><img src="docs/media/{preview.name}" width="420" alt="{html.escape(description, quote=True)}"></a><br>'
            sidecar = media / f"{example}.json"
            if sidecar.is_file():
                caption = json.loads(sidecar.read_text()).get("caption", "")
                if caption:
                    cell += html.escape(caption) + "<br>"
        elif require_videos:
            raise ValueError(f"Missing video or preview for {example}")
        else:
            cell += f"Video not recorded yet: `uv run --locked python tools/record_examples.py {example}`<br>"
        cell += f"`./docker/run.sh {example}`"
        cells.append(cell.replace("|", "&#124;"))
    text.append("| Example | Example |\n| --- | --- |")
    text.extend(f"| {cells[i]} | {cells[i + 1] if i + 1 < len(cells) else ''} |" for i in range(0, len(cells), 2))
    text.extend(
        [
            "\n## Regenerate documentation\n",
            "```bash\npython3 tools/build_readme.py\npython3 tools/build_readme.py --check\nuv run --locked python tools/record_examples.py --all\npython3 tools/build_readme.py --require-videos\n```\n",
            "README generation uses only Python's standard library and discovers examples from their launcher. "
            "Recording needs the `examples` extra, `ffmpeg`, and OpenGL. "
            "`docs/videos.json` stores optional capture arguments; it does not define the example list. "
            "`tools/video_scenarios.py`, when present, scripts interactions for recording. "
            "Each clip has a metadata file recording arguments, frame count and capture conditions.\n",
            "## Validate\n",
            "```bash\nuv run --locked ruff check .\nuv run --locked ruff format --check .\nuv run --locked python -m unittest discover -s tests -v\nNEWTON_TEST_DEVICE=cuda:0 uv run --locked python -m unittest discover -s tests -v\nuv build\n```\n",
        ]
    )
    if (root / "docs" / "validation.md").is_file():
        text.append("See [validation scope and results](docs/validation.md).\n")
    if (root / "tools" / "new_solver.py").is_file():
        text.extend(
            [
                "## Create a solver\n",
                "```bash\nuv run --locked python tools/new_solver.py ../newton-solver-custom --name newton-solver-custom\n```\n",
                "The generated package has its own code, lockfile, Docker scripts and README tools. "
                "Replace the starter equations and update `docs/method.md` with the actual paper and gradient contract.\n",
            ]
        )
    notices = next((p.name for p in root.glob("THIRD_PARTY_NOTICES*") if p.is_file()), None)
    text.append(
        "License: [Apache-2.0](LICENSE)."
        + (f" Required third-party attribution is in [{notices}]({notices})." if notices else "")
    )
    return "\n".join(text) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if README differs from generated content.")
    parser.add_argument("--require-videos", action="store_true", help="Fail if any discovered example lacks a clip.")
    args = parser.parse_args()
    try:
        result = make_readme(require_videos=args.require_videos)
    except (ValueError, OSError) as error:
        parser.exit(1, f"{error}\n")
    path = ROOT / "README.md"
    if args.check:
        if not path.is_file() or path.read_text() != result:
            parser.exit(1, "README.md is stale; run python3 tools/build_readme.py\n")
        print("README.md is current")
    else:
        path.write_text(result)
        print("Generated README.md")


if __name__ == "__main__":
    main()
